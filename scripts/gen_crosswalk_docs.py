"""Generate docs/iso19115-cdif-crosswalk.md from the crosswalk code.

Usage:  python scripts/gen_crosswalk_docs.py           write the file
        python scripts/gen_crosswalk_docs.py --check   exit 1 if stale

The mapping rules come from crosswalk.iso19115.MAPPINGS and
crosswalk.codata; the results section runs every bundled ISO record
through the crosswalk and the MCP server's validator. Needs the vendored
CODATA profile (see README), like the server itself.
"""

import argparse
import contextlib
import io
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from crosswalk import MAPPINGS, crosswalk  # noqa: E402
from crosswalk.codata import (  # noqa: E402
    NOT_IMPLEMENTED,
    REFERENCES,
    SPREADSHEET,
)
from crosswalk.iso19115 import DATASET_SCOPES  # noqa: E402

OUT = ROOT / "docs" / "iso19115-cdif-crosswalk.md"
FIXTURES = ROOT / "tests" / "fixtures" / "iso"

# Why each bundled record that fails CDIF validation fails. Generation
# stops if the set of failing records changes, so this cannot go stale.
FAILURE_REASONS = {
    "auscope-gsv-mineral-occurrences.xml": (
        "the source record states no licence or access conditions, so "
        "CDIF's required `schema:license` or `schema:conditionsOfAccess` "
        "cannot be filled (a real gap in the source)."
    ),
    "auscope-calperum-czo.xml": (
        "its funder has no identifier, and CDIF's validation frame drops "
        "such funders (problem 2 below)."
    ),
}

INTRO = f"""\
# ISO 19115 to CDIF Discovery crosswalk

<!-- Generated by scripts/gen_crosswalk_docs.py from crosswalk/iso19115.py
and crosswalk/codata.py. Do not edit by hand: change the code and
regenerate. -->

This crosswalk converts ISO 19115 metadata records, as published by
GeoNetwork catalogues, into JSON-LD that follows the [CDIF Discovery
profile](https://w3id.org/cdif/discovery/1.1) (version 1.1). It reads two
XML encodings:

- **ISO 19115-3** (namespace `mdb` 2.0), the encoding of ISO 19115-1:2014.
  TERN, IMOS/AODN and AuScope publish nearly all their records this way.
- **ISO 19139** (namespace `gmd`), the encoding of ISO 19115:2003.

The rules follow CODATA's crosswalk spreadsheet
(`{SPREADSHEET}`, sheet "crosswalks"). Each rule below gives the
spreadsheet rows it is based on and says where this tool departs from
them. The spreadsheet is an archived working document, not a normative
part of CDIF.

Only records that describe data are converted, because CDIF Discovery
describes datasets. Accepted resource scopes (`MD_ScopeCode`):
{", ".join(f"`{s}`" for s in sorted(DATASET_SCOPES))}. A record with no
scope is treated as a dataset. Other scopes, such as `service`, are
reported as out of scope.

## Using it

- From an MCP client: `crosswalk_iso19115(url=...)` or
  `crosswalk_iso19115(example=...)`, and
  `crosswalk_geonetwork_record(catalogue=..., uuid=...)`. Each converts
  the record and validates the result against the CDIF JSON Schema and
  SHACL rules.
- From Python: `crosswalk.crosswalk(xml_bytes)` returns
  `{{"record": ..., "report": ...}}`.

The report says what was done, so that nothing is hidden:

- `mapped`: the CDIF properties produced, with the ISO elements they were
  copied from.
- `inferences_and_fallbacks`: every value that was inferred or taken
  from a fallback source.
- `missing_required`: CDIF required properties the ISO record cannot
  supply.
- `unmapped`: ISO sections the crosswalk ignored.
- `out_of_scope`: why a record was not converted (only when it was not).
"""

CDIF_ISSUES = """\
## Problems found in CDIF itself

Building the crosswalk exposed three problems in the CDIF artefacts. They
affect any CDIF producer, not only this one.

1. **Invalid JSON-LD for WKT geometry.** The CDIF JSON Schema, and
   `exampleCDIFDiscoveryComplete.json`, give `geosparql:asWKT` an array
   `@type`. JSON-LD 1.1 requires a value object's `@type` to be a single
   IRI, so JSON-LD processors reject the example (pyld: "invalid typed
   value"). This crosswalk writes a string `@type`, which is valid
   JSON-LD.
2. **Funders without identifiers are dropped by the validation frame.**
   In `CDIFDiscoveryDoc-frame.jsonld`, the `schema:funder` sub-frame lists
   only `schema:identifier`. JSON-LD framing then matches only funders
   that have an identifier, so a funder known only by name disappears
   from the framed document, and the JSON Schema reports `schema:funder`
   as missing although it is present.
3. **Dataset rules also apply to the catalog record.** CDIF types the
   metadata record in `schema:subjectOf` as `schema:Dataset`, so the
   SHACL Dataset recommendations (creator, description, keywords...) are
   also checked on it. The MCP server's `validate_cdif` reports these
   separately, as `catalog_record_results`, so that they are not read as
   gaps in the dataset.
"""


def cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def anchor(prop: str) -> str:
    return prop.lower().replace(":", "").replace("@", "")


def mapping_sections() -> list[str]:
    out = [
        "## Mapping rules",
        "",
        "| CDIF property | ISO 19115-3 source | CODATA rows | Differs |",
        "| --- | --- | --- | --- |",
    ]
    for m in MAPPINGS:
        ref = REFERENCES[m.cdif]
        out.append(
            f"| [`{m.cdif}`](#{anchor(m.cdif)}) | `{cell(m.iso19115_3)}` "
            f"| {ref.rows or '-'} | {'yes' if ref.differs else ''} |"
        )
    out.append("")
    for m in MAPPINGS:
        ref = REFERENCES[m.cdif]
        out += [
            f"### `{m.cdif}`",
            "",
            f"- **ISO 19115-3:** `{m.iso19115_3}`",
            f"- **ISO 19139:** `{m.iso19139}`",
            f"- **Rule:** {cell(m.rule)}",
            f"- **CODATA rows:** {ref.rows or 'none'}",
        ]
        if ref.differs:
            out.append(f"- **Differs from CODATA:** {cell(ref.differs)}")
        out.append("")
    return out


def not_implemented_section() -> list[str]:
    out = [
        "## Not mapped yet",
        "",
        "CODATA crosswalk rows with an ISO source that this tool does not "
        "map yet.",
        "",
        "| CDIF property | ISO source | CODATA rows | Why |",
        "| --- | --- | --- | --- |",
    ]
    out += [
        f"| `{n.cdif}` | `{n.iso}` | {n.rows} | {cell(n.why)} |"
        for n in NOT_IMPLEMENTED
    ]
    return [*out, ""]


def results_section() -> list[str]:
    import DemoMcpServer as srv

    manifest = json.loads((FIXTURES / "manifest.json").read_text("utf-8"))
    rows, unmapped, inferences = [], Counter(), Counter()
    converted, failing = 0, set()
    for rec in manifest["records"]:
        xml = (FIXTURES / rec["file"]).read_bytes()
        with contextlib.redirect_stdout(io.StringIO()):
            out = crosswalk(xml)
        report = out["report"]
        name = f"`{rec['file']}`"
        if out["record"] is None:
            reason = report["out_of_scope"].split(". ")[0]
            rows.append(
                f"| {name} | {report['dialect']} | out of scope: "
                f"{cell(reason)} | | | |"
            )
            continue
        converted += 1
        v = srv._validate_one(out["record"])
        if not v["valid"]:
            failing.add(rec["file"])
        c = v["shacl"]["counts"]
        unmapped.update(u["element"] for u in report["unmapped"])
        inferences.update(set(report["inferences_and_fallbacks"]))
        rows.append(
            f"| {name} | {report['dialect']} "
            f"| {'valid' if v['valid'] else '**not valid**'} "
            f"| {c['Violation']} / {c['Warning']} / {c['Info']} "
            f"| {cell(', '.join(report['missing_required'])) or 'none'} "
            f"| {len(report['inferences_and_fallbacks'])} |"
        )
    if failing != set(FAILURE_REASONS):
        raise SystemExit(
            f"Records failing validation changed (now: {sorted(failing)}). "
            f"Update FAILURE_REASONS in {Path(__file__).name} to explain "
            f"them."
        )
    out = [
        "## Results on NCRIS facility records",
        "",
        f"The {len(manifest['records'])} bundled records from the TERN, "
        "IMOS/AODN and AuScope GeoNetwork catalogues (see "
        "`tests/fixtures/iso/`), converted and checked with the MCP "
        "server's validator (CDIF JSON Schema and SHACL rules). SHACL "
        "counts include results on the catalog record.",
        "",
        "| Record | Dialect | CDIF | SHACL violations / warnings / info "
        "| Missing required | Inferences |",
        "| --- | --- | --- | --- | --- | --- |",
        *rows,
        "",
        "Why the records that fail do so:",
        "",
        *(f"- `{f}`: {why}" for f, why in sorted(FAILURE_REASONS.items())),
        "",
        "### Inferences and fallbacks",
        "",
        f"How often each was needed, across the {converted} converted "
        "records:",
        "",
        "| Records | Inference or fallback |",
        "| --- | --- |",
        *(
            f"| {n} | {cell(msg)} |"
            for msg, n in sorted(
                inferences.items(), key=lambda kv: (-kv[1], kv[0])
            )
        ),
        "",
        "### ISO sections left unmapped",
        "",
        f"Sections ignored by the crosswalk, and in how many of the "
        f"{converted} converted records they occur:",
        "",
        "| Records | ISO section |",
        "| --- | --- |",
        *(
            f"| {n} | `{el}` |"
            for el, n in sorted(
                unmapped.items(), key=lambda kv: (-kv[1], kv[0])
            )
        ),
        "",
    ]
    return out


def render() -> str:
    parts = [
        INTRO,
        *mapping_sections(),
        *not_implemented_section(),
        *results_section(),
        CDIF_ISSUES,
    ]
    return "\n".join(parts).rstrip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument(
        "--check", action="store_true", help="exit 1 if the file is stale"
    )
    args = ap.parse_args()
    text = render()
    if args.check:
        current = OUT.read_text("utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date; regenerate it.")
            return 1
        return 0
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(text, "utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
